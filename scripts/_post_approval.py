    "**審査日時:** 2026-04-22（最終確定版）\n\n"
    "全スロット合格。チカキャラ・中級者・40字改行・絵文字・〜してる語尾 確認済み。\n\n"
    "---\n"
    "### 📋 推奨投稿案（3時間帯・オーナー一括承認用）\n\n"
    "**🌅 SLOT_1【7時・即時投稿】**\n"
